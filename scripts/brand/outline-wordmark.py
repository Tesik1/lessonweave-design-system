"""Outlines the LessonWeave wordmark and the module names into SVG paths:
brand/src/wordmark.json and brand/src/modules.json.

Outfit is used only for the wordmark and the module names in the header lockups, and
apps never load it, so both ship as paths. Run this only when the wordmark or a module
name changes; the output is committed and scripts/brand/build.mjs builds every logo
file from it.

    python -m pip install fonttools brotli uharfbuzz
    python scripts/brand/outline-wordmark.py

Settings follow the branding: Outfit 600, kerning on (as a browser renders it). The
wordmark has letter-spacing -0.02em, "Lesson" in ink and "Weave" in accent; module
names have none.
"""

import io
import json
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "scripts" / "brand" / "fonts" / "Outfit-latin.woff2"
WEIGHT = 600
MODULES = {"flashcards": "Flashcards", "practice": "Practice", "planner": "Planner", "insights": "Insights"}

font = TTFont(FONT)
upem = font["head"].unitsPerEm
glyphs = font.getGlyphSet(location={"wght": WEIGHT})
order = font.getGlyphOrder()

# HarfBuzz does not read WOFF2, so it gets the decompressed font.
sfnt = io.BytesIO()
plain = TTFont(FONT)
plain.flavor = None
plain.save(sfnt)
hb_font = hb.Font(hb.Face(sfnt.getvalue()))
hb_font.set_variations({"wght": WEIGHT})


def outline(parts, letter_spacing):
    """Paths of each (key, text) part set as one line; returns (paths, advance)."""
    text = "".join(t for _, t in parts)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    # Browsers turn off optional ligatures when letter-spacing is set; kerning stays.
    hb.shape(hb_font, buf, {"kern": True, "liga": False, "clig": False})

    spacing = letter_spacing * upem
    pens = {key: SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip(".")) for key, _ in parts}
    part_of = []
    for key, t in parts:
        part_of += [key] * len(t)

    x = 0.0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        key = part_of[info.cluster]
        # Font units are y-up; SVG is y-down with the baseline at y = 0.
        pen = TransformPen(pens[key], (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset))
        glyphs[name].draw(pen)
        x += pos.x_advance + spacing
    return {key: pens[key].getCommands() for key, _ in parts}, round(x, 1)


def write(name, data):
    out = ROOT / "brand" / "src" / name
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(out.relative_to(ROOT))


hhea = font["hhea"]
paths, advance = outline([("lesson", "Lesson"), ("weave", "Weave")], -0.02)
write(
    "wordmark.json",
    {
        "note": "Generated by scripts/brand/outline-wordmark.py. Font units, baseline at y = 0.",
        "unitsPerEm": upem,
        "ascender": hhea.ascent,
        "descender": hhea.descent,
        # Width of the CSS text box: every glyph advance plus letter-spacing after each glyph.
        "advance": advance,
        "paths": paths,
    },
)

modules = {}
for key, text in MODULES.items():
    paths, advance = outline([(key, text)], 0)
    modules[key] = {"text": text, "advance": advance, "path": paths[key]}
write(
    "modules.json",
    {
        "note": "Generated by scripts/brand/outline-wordmark.py. Font units, baseline at y = 0.",
        "unitsPerEm": upem,
        "capHeight": font["OS/2"].sCapHeight,
        "modules": modules,
    },
)
